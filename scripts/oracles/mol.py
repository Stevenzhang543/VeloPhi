def cell_volume(c):
    al, be, ga = (math.radians(c[k]) for k in ('alpha', 'beta', 'gamma'))
    ca, cb, cg = math.cos(al), math.cos(be), math.cos(ga)
    return c['a'] * c['b'] * c['c'] * math.sqrt(1 - ca * ca - cb * cb - cg * cg + 2 * ca * cb * cg)


ELEMENT_BASIS = {'fcc': 4, 'bcc': 2, 'hcp': 2, 'diamond': 8, 'graphite': 4}


def crystal_reference(c):
    from mendeleev import element
    V = cell_volume(c)
    if 'basis' in c:
        mass = sum(float(element(b[0]).atomic_weight) for b in c['basis'])
        count = len(c['basis'])
    else:
        count = ELEMENT_BASIS[c['structure']]
        mass = count * float(element(c['element']).atomic_weight)
    ref = {'volume': V, 'atoms': count, 'density': mass * U_IN_G / (V * 1e-24)}
    a = c['a']
    s = c['structure']
    if s == 'fcc':
        ref.update(cn=12, nearest=a / math.sqrt(2), packing=math.pi / (3 * math.sqrt(2)))
    elif s == 'bcc':
        ref.update(cn=8, nearest=a * math.sqrt(3) / 2, packing=math.pi * math.sqrt(3) / 8)
    elif s == 'diamond':
        ref.update(cn=4, nearest=a * math.sqrt(3) / 4, packing=math.pi * math.sqrt(3) / 16)
    elif s == 'hcp':
        # two shells of six, treated as one; hard spheres touch along the shorter contact
        d1, d2 = a, math.sqrt(a * a / 3 + c['c'] ** 2 / 4)
        r = min(d1, d2) / 2
        ref.update(cn=12, nearest=min(d1, d2), packing=2 * 4 / 3 * math.pi * r ** 3 / V)
    elif s == 'graphite':
        ref.update(cn=3, nearest=a / math.sqrt(3))
    elif s == 'rock-salt':
        ref.update(cn=6, nearest=a / 2)
    elif s == 'caesium-chloride':
        ref.update(cn=8, nearest=a * math.sqrt(3) / 2)
    elif s == 'zinc-blende':
        ref.update(cn=4, nearest=a * math.sqrt(3) / 4)
    elif s == 'fluorite':
        ref.update(cn=8, nearest=a * math.sqrt(3) / 4)
    elif s == 'perovskite':
        ref.update(cn=12, nearest=a / math.sqrt(2))
    elif s == 'rutile':
        ref.update(cn=6)
    return ref



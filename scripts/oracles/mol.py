def angle(p, i, j, k):
    u, v = p[i] - p[j], p[k] - p[j]
    return math.degrees(math.acos(max(-1.0, min(1.0, float(np.dot(u, v) / np.linalg.norm(u) / np.linalg.norm(v))))))


def dihedral(p, i, j, k, l):
    """IUPAC sign: positive when the far bond is rotated clockwise looking from j to k."""
    b0, b1, b2 = p[i] - p[j], p[k] - p[j], p[l] - p[k]
    b1 = b1 / np.linalg.norm(b1)
    v, w = b0 - np.dot(b0, b1) * b1, b2 - np.dot(b2, b1) * b1
    return math.degrees(math.atan2(float(np.dot(np.cross(b1, v), w)), float(np.dot(v, w))))


def molecule_reference(m):
    p = np.array(m['xyz']).reshape(-1, 3)
    n = len(m['atoms'])
    nb = [[] for _ in range(n)]
    bonds = []
    for t in range(0, len(m['bonds']), 3):
        i, j = int(m['bonds'][t]), int(m['bonds'][t + 1])
        nb[i].append(j)
        nb[j].append(i)
        bonds.append({'i': i, 'j': j, 'length': float(np.linalg.norm(p[i] - p[j]))})
    angles = []
    for j in range(n):
        ns = sorted(nb[j])
        for a in range(len(ns)):
            for b in range(a + 1, len(ns)):
                angles.append({'i': ns[a], 'j': j, 'k': ns[b], 'angle': angle(p, ns[a], j, ns[b])})
    ref = {'bonds': bonds, 'angles': angles}
    if 'charges' in m:
        q = np.array(m['charges'])
        mu = (q[:, None] * p).sum(axis=0) * E_ANGSTROM_IN_DEBYE
        ref['dipole'] = {'vector': [float(x) for x in mu], 'magnitude': float(np.linalg.norm(mu))}
    if m['id'] in VSEPR:
        atom, cls, geometry, lone = VSEPR[m['id']]
        ref['vsepr'] = {'atom': atom, 'class': cls, 'geometry': geometry, 'lonePairs': lone}
    if m['id'] == 'ethanol':
        # H–O–C–C and the three H–C–C–O
        o = m['atoms'].index('O')
        ho = [j for j in nb[o] if m['atoms'][j] == 'H'][0]
        c1 = [j for j in nb[o] if m['atoms'][j] == 'C'][0]
        c0 = [j for j in nb[c1] if m['atoms'][j] == 'C'][0]
        dih = [{'atoms': [ho, o, c1, c0], 'dihedral': dihedral(p, ho, o, c1, c0)}]
        for hx in sorted(j for j in nb[c0] if m['atoms'][j] == 'H'):
            dih.append({'atoms': [hx, c0, c1, o], 'dihedral': dihedral(p, hx, c0, c1, o)})
        ref['dihedrals'] = dih
    return ref



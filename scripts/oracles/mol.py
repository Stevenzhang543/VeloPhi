def radial(n, l, r, Z=1.0):
    """R_nl(r) in Å^-3/2 (r in Å)."""
    from scipy.special import genlaguerre, factorial
    rho = 2 * Z * r / (n * BOHR)
    norm = math.sqrt((2 * Z / (n * BOHR)) ** 3 * factorial(n - l - 1) / (2 * n * factorial(n + l)))
    return norm * np.exp(-rho / 2) * rho ** l * genlaguerre(n - l - 1, 2 * l + 1)(rho)


def real_harmonic(l, m, x, y, z):
    import scipy.special as sp
    r = math.sqrt(x * x + y * y + z * z)
    theta, phi = math.acos(z / r), math.atan2(y, x)
    if hasattr(sp, 'sph_harm_y'):
        Y = lambda mm: complex(sp.sph_harm_y(l, mm, theta, phi))
    else:
        Y = lambda mm: complex(sp.sph_harm(mm, l, phi, theta))
    if m == 0:
        return Y(0).real
    if m > 0:
        return math.sqrt(2) * (-1) ** m * Y(m).real
    return math.sqrt(2) * (-1) ** m * Y(-m).imag


POINTS = [(0.31, 0.17, 0.52), (-0.83, 0.44, 0.29), (1.9, -1.2, 0.7), (-0.4, -2.6, -1.1), (3.7, 2.2, -4.1), (0.05, 6.3, 1.4), (-7.9, -0.6, 5.2)]


def orbitals():
    out = []
    for n in range(1, 5):
        for l in range(n):
            for m in range(-l, l + 1):
                for Z in ((1.0, 2.0) if (n, l, m) in ((1, 0, 0), (3, 2, 0)) else (1.0,)):
                    psi = [float(radial(n, l, math.sqrt(x * x + y * y + z * z), Z) * real_harmonic(l, m, x, y, z)) for x, y, z in POINTS]
                    out.append({'n': n, 'l': l, 'm': m, 'Z': Z, 'radialNodes': n - l - 1, 'angularNodes': l, 'meanRadius': BOHR * (3 * n * n - l * (l + 1)) / (2 * Z), 'psi': psi})
    return {'points': [c for p in POINTS for c in p], 'cases': out}


